import { RULES } from "../catalog.js";
import type { AuditResult, Finding } from "../types.js";
import { SEVERITIES } from "../types.js";
import { capitalize, countBySeverity, plural } from "./common.js";

export interface MarkdownOptions {
  name: string;
  version: string;
  /** Optional ISO date printed in the header. Omitted by default so output is reproducible. */
  date?: string;
}

/** What no run of this tool covers, regardless of the project. */
export const NOT_CHECKED: readonly string[] = [
  "Runtime behaviour. Nothing was executed, no request was sent and no database was queried. Row level security is judged from the SQL in the migrations, not from the policies that are live in a database.",
  "Anything configured outside the repository: Supabase dashboard settings (auth providers, redirect URL allow-list, email confirmation, storage bucket policies), Stripe dashboard settings and webhook endpoints, hosting environment variables, DNS, CDN and WAF rules.",
  "Database objects other than tables and policies: views (security_invoker), SECURITY DEFINER functions, grants, triggers, extensions and realtime publications.",
  "Authorization logic beyond the patterns the rules recognise. A route that calls an auth helper is treated as authenticated; whether the check is correct, complete or applied to every branch is not evaluated. Business-rule authorization (roles, plans, seat limits) is not evaluated.",
  "Data flow across files. Taint is tracked inside one function; values that pass through an imported helper are treated as no longer client-controlled, and imported data-access helpers are not followed.",
  "Dependency vulnerabilities. There is no advisory database in this tool; run npm audit (or your package manager's equivalent) and review lockfile changes.",
  "Secrets in git history, in build artifacts, in files outside the scanned extensions, and in third-party services.",
  "Denial of service, performance, accessibility, privacy and legal compliance, and any vulnerability class not named in the rule list below.",
  "Findings are candidates with evidence, not proof of exploitability. False positives are possible and a clean report is not evidence that the application is secure.",
];

function renderFinding(f: Finding, id: string): string[] {
  const lines: string[] = [];
  lines.push(`### ${id}: ${f.title}`);
  lines.push("");
  lines.push(`- **Severity:** ${capitalize(f.severity)}`);
  lines.push(`- **Rule:** \`${f.rule}\``);
  lines.push(`- **Location:** \`${f.file}:${f.line}\``);
  lines.push("");
  lines.push(`**Why it matters.** ${f.message}`);
  lines.push("");
  lines.push("**Evidence**");
  lines.push("");
  lines.push("```");
  lines.push(...f.evidence.split("\n"));
  lines.push("```");
  lines.push("");
  lines.push(`**Recommended fix.** ${f.fix}`);
  lines.push("");
  return lines;
}

const escapeCell = (text: string): string => text.replace(/\|/g, "\\|");

export function renderMarkdown(result: AuditResult, options: MarkdownOptions): string {
  const s = result.stats;
  const counts = countBySeverity(result.findings);
  const out: string[] = [];
  out.push(`# Security audit report: ${options.name}`);
  out.push("");
  out.push(`Generated by saas-audit ${options.version}${options.date ? ` on ${options.date}` : ""}.`);
  out.push("");
  out.push("> This is the output of a static analyser run over a source tree. It is not a penetration test and not a substitute for a human code review. Every finding below points at a file and line so it can be checked by hand.");
  out.push("");
  out.push("## Summary");
  out.push("");
  out.push("| Severity | Findings |");
  out.push("| --- | ---: |");
  for (const sev of SEVERITIES) out.push(`| ${capitalize(sev)} | ${counts[sev]} |`);
  out.push(`| **Total** | **${result.findings.length}** |`);
  out.push("");
  if (result.suppressed.length > 0) {
    out.push(`${result.suppressed.length} further finding${result.suppressed.length === 1 ? " was" : "s were"} suppressed by inline comments and ${result.suppressed.length === 1 ? "is" : "are"} listed at the end.`);
    out.push("");
  }
  out.push(`**Scope.** ${plural(s.filesScanned, "file")} read: ${s.sourceFiles} JavaScript/TypeScript, ${s.sqlFiles} SQL (${plural(s.tablesFound, "public table")} and ${plural(s.policiesFound, "policy", "policies")} parsed), ${plural(s.routeHandlers, "route handler")}, ${plural(s.serverActions, "server action")} and ${plural(s.clientComponents, "client component")} recognised.`);
  out.push("");

  if (result.findings.length > 0) {
    out.push("## Findings at a glance");
    out.push("");
    out.push("| ID | Severity | Rule | Location | Title |");
    out.push("| --- | --- | --- | --- | --- |");
    result.findings.forEach((f, i) => {
      const id = `SA-${String(i + 1).padStart(3, "0")}`;
      out.push(`| ${id} | ${capitalize(f.severity)} | \`${f.rule}\` | \`${f.file}:${f.line}\` | ${escapeCell(f.title)} |`);
    });
    out.push("");
    out.push("## Findings");
    out.push("");
    result.findings.forEach((f, i) => out.push(...renderFinding(f, `SA-${String(i + 1).padStart(3, "0")}`)));
  } else {
    out.push("## Findings");
    out.push("");
    out.push("No findings. See the limits below before reading anything into that.");
    out.push("");
  }

  if (result.suppressed.length > 0) {
    out.push("## Suppressed findings");
    out.push("");
    out.push("These were silenced with `saas-audit-ignore` comments in the source. The comment is the place to read the reason.");
    out.push("");
    out.push("| Severity | Rule | Location | Title |");
    out.push("| --- | --- | --- | --- |");
    for (const f of result.suppressed) out.push(`| ${capitalize(f.severity)} | \`${f.rule}\` | \`${f.file}:${f.line}\` | ${escapeCell(f.title)} |`);
    out.push("");
  }

  if (result.warnings.length > 0) {
    out.push("## Warnings");
    out.push("");
    for (const w of result.warnings) out.push(`- ${w}`);
    out.push("");
  }

  out.push("## What was not checked");
  out.push("");
  if (result.notes.length > 0) {
    out.push("For this project in particular:");
    out.push("");
    for (const n of result.notes) out.push(`- ${n}`);
    out.push("");
    out.push("In general:");
    out.push("");
  }
  for (const n of NOT_CHECKED) out.push(`- ${n}`);
  out.push("");

  out.push("## Rules applied");
  out.push("");
  out.push("| Rule | Checks |");
  out.push("| --- | --- |");
  for (const r of RULES) out.push(`| \`${r.id}\` | ${escapeCell(r.summary)} |`);
  out.push("");
  return out.join("\n");
}
