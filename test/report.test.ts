import { describe, expect, it } from "vitest";
import { countBySeverity, filterMinSeverity, plural, projectName } from "../src/report/common.js";
import { renderHuman } from "../src/report/human.js";
import { renderJson } from "../src/report/json.js";
import { NOT_CHECKED, renderMarkdown } from "../src/report/markdown.js";
import { projectFromFiles } from "../src/project.js";
import type { AuditResult, Finding, SuppressedFinding } from "../src/types.js";
import { DEFAULT_CONFIG } from "../src/config.js";
import { RULES } from "../src/catalog.js";

function finding(overrides: Partial<Finding> = {}): Finding {
  return { rule: "api-route-no-auth", severity: "high", file: "app/api/a/route.ts", line: 4, title: "GET handler reads data without an auth check", message: "Why text.", evidence: "L4: export async function GET() {\nL5: await supabase.from(\"a\").select()", fix: "Fix text.", ...overrides };
}

function result(findings: Finding[], extra: Partial<AuditResult> = {}): AuditResult {
  return {
    findings,
    suppressed: [],
    warnings: [],
    skipped: [],
    notes: [],
    stats: { filesScanned: 12, sourceFiles: 8, sqlFiles: 1, tablesFound: 3, policiesFound: 2, routeHandlers: 4, serverActions: 1, clientComponents: 2 },
    config: { ...DEFAULT_CONFIG, source: null, skippedDirs: [], ignoredPathCount: 0 },
    ...extra,
  };
}

function suppressedFinding(overrides: Partial<Finding> = {}, by = "inline comment"): SuppressedFinding {
  return { ...finding(overrides), suppressedBy: by };
}

const opts = { name: "demo", version: "9.9.9" };

describe("report helpers", () => {
  it("counts findings by severity and filters by minimum severity", () => {
    const fs = [finding({ severity: "critical" }), finding({ severity: "high" }), finding({ severity: "high" }), finding({ severity: "info" })];
    expect(countBySeverity(fs)).toEqual({ critical: 1, high: 2, medium: 0, low: 0, info: 1 });
    expect(filterMinSeverity(fs, "high").map((f) => f.severity)).toEqual(["critical", "high", "high"]);
    expect(filterMinSeverity(fs, "info")).toHaveLength(4);
  });

  it("takes the project name from package.json, else the directory name", () => {
    expect(projectName(projectFromFiles({ "package.json": '{"name":"acme-app"}' }, { root: "/x/y/dirname" }))).toBe("acme-app");
    expect(projectName(projectFromFiles({ "package.json": "{ broken" }, { root: "/x/y/dirname" }))).toBe("dirname");
    expect(projectName(projectFromFiles({}, { root: "/x/y/dirname" }))).toBe("dirname");
  });

  it("pluralises", () => {
    expect(plural(1, "file")).toBe("1 file");
    expect(plural(0, "file")).toBe("0 files");
    expect(plural(2, "policy", "policies")).toBe("2 policies");
  });
});

describe("markdown report", () => {
  const fs = [finding({ severity: "critical", title: "A | B" }), finding({ severity: "high", file: "b.ts", line: 9 })];
  const md = renderMarkdown(result(fs, { notes: ["No migrations."], warnings: ["x.ts:1: stale"] }), opts);

  it("opens with the title, a disclaimer and a summary table by severity", () => {
    expect(md.startsWith("# Security audit report: demo\n")).toBe(true);
    expect(md).toContain("Generated by saas-audit 9.9.9.");
    expect(md).toContain("not a penetration test");
    expect(md).toContain("| Severity | Findings |\n| --- | ---: |\n| Critical | 1 |\n| High | 1 |\n| Medium | 0 |\n| Low | 0 |\n| Info | 0 |\n| **Total** | **2** |");
  });

  it("states the scope from the stats", () => {
    expect(md).toContain("**Scope.** 12 files read: 8 JavaScript/TypeScript, 1 SQL (3 public tables and 2 policies parsed), 4 route handlers, 1 server action and 2 client components recognised.");
  });

  it("lists findings at a glance and then each finding with evidence and fix", () => {
    expect(md).toContain("| SA-001 | Critical | `api-route-no-auth` | `app/api/a/route.ts:4` | A \\| B |");
    expect(md).toContain("### SA-002: GET handler reads data without an auth check");
    expect(md).toContain("- **Location:** `b.ts:9`");
    expect(md).toContain("**Why it matters.** Why text.");
    expect(md).toContain('```\nL4: export async function GET() {\nL5: await supabase.from("a").select()\n```');
    expect(md).toContain("**Recommended fix.** Fix text.");
  });

  it("has a 'What was not checked' section with project notes first, then the general list, and the rules table", () => {
    const section = md.slice(md.indexOf("## What was not checked"));
    expect(section).toContain("For this project in particular:\n\n- No migrations.");
    for (const line of NOT_CHECKED) expect(section).toContain(line);
    for (const r of RULES) expect(md).toContain(`| \`${r.id}\` |`);
    expect(md.indexOf("## Findings")).toBeLessThan(md.indexOf("## What was not checked"));
  });

  it("prints warnings, suppressed findings and an optional date", () => {
    const withSuppressed = renderMarkdown(result([], { suppressed: [suppressedFinding()], warnings: ["x.ts:1: stale"] }), { ...opts, date: "2026-01-31" });
    expect(withSuppressed).toContain("Generated by saas-audit 9.9.9 on 2026-01-31.");
    expect(withSuppressed).toContain("1 further finding was not counted");
    expect(withSuppressed).toContain("## Findings not counted");
    expect(withSuppressed).toContain("## Warnings\n\n- x.ts:1: stale");
  });

  it("says so plainly when there are no findings, and never claims the project is secure", () => {
    const empty = renderMarkdown(result([]), opts);
    expect(empty).toContain("No findings. See the limits below before reading anything into that.");
    expect(empty).toContain("a clean report is not evidence that the application is secure");
    expect(empty).not.toMatch(/all clear|no issues|passed|certified/i);
  });
});

describe("json report", () => {
  it("is stable, has a summary and carries every field of a finding", () => {
    const r = result([finding({ severity: "critical" }), finding()], { suppressed: [suppressedFinding({ line: 99 })] });
    const a = renderJson(r, opts);
    expect(renderJson(r, opts)).toBe(a);
    const doc = JSON.parse(a);
    expect(doc.tool).toEqual({ name: "saas-audit", version: "9.9.9" });
    expect(doc.project).toBe("demo");
    expect(doc.summary).toEqual({ total: 2, suppressed: 1, bySeverity: { critical: 1, high: 1, medium: 0, low: 0, info: 0 } });
    expect(doc.complete).toBe(true);
    expect(Object.keys(doc.findings[0])).toEqual(["rule", "severity", "file", "line", "title", "message", "evidence", "fix"]);
    expect(doc.suppressed[0].line).toBe(99);
    expect(a.endsWith("\n")).toBe(true);
  });
});

describe("human report", () => {
  const r = result([finding({ severity: "critical" }), finding({ severity: "low" })], { notes: ["Note one."], warnings: ["warn"], suppressed: [suppressedFinding()] });

  it("prints a block per finding with why, evidence and fix, and a total line", () => {
    const text = renderHuman(r, { ...opts, color: false });
    expect(text).toContain("saas-audit 9.9.9: demo");
    expect(text).toContain("CRITICAL api-route-no-auth  app/api/a/route.ts:4");
    expect(text).toContain("  Why:      Why text.");
    expect(text).toContain('  Evidence: L4: export async function GET() {\n            L5: await supabase.from("a").select()');
    expect(text).toContain("2 findings: 1 critical, 0 high, 0 medium, 1 low, 0 info.");
    expect(text).toContain("1 finding not counted:");
    expect(text).toContain("  - high api-route-no-auth app/api/a/route.ts:4 (inline comment)");
    expect(text).toContain("warning: warn");
    expect(text).toContain("  - Note one.");
  });

  it("emits ANSI colours only when asked", () => {
    expect(renderHuman(r, { ...opts, color: false })).not.toContain("\u001b[");
    expect(renderHuman(r, { ...opts, color: true })).toContain("\u001b[");
  });

  it("reports a clean run without alarm words", () => {
    const text = renderHuman(result([]), { ...opts, color: false });
    expect(text).toContain("No findings.");
    expect(text).toContain("not a penetration test");
  });
});
